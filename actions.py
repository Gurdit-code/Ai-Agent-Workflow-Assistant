def classify_keywords(words=""):
    rules = {
        "Transactional": (("buy", "purchase", "order now"), "Product page", "High"),
        "Commercial": (("best", "review", "compare", "top"), "Category page", "Medium"),
        "Informational": (("how", "what", "why", "guide"), "Blog or guide", "Low"),
        "Navigational": (("brand", "official website", "login"), "Brand page", "Low"),
    }
    if not words.strip():
        return {"error": "Enter one or more keywords."}
    found, results = set(), []
    for word in words.split(","):
        word = word.strip()
        if not word or word.lower() in found:
            continue
        found.add(word.lower())
        intent, page, priority = "Unclassified", "Review manually", "Low"
        for label, (terms, target, level) in rules.items():
            if any(term in word.lower() for term in terms):
                intent, page, priority = label, target, level
                break
        results.append({"keyword": word, "intent": intent,
            "target_page": page, "priority": priority})
    return results


def assign_employee(skill="", task="", priority="Normal", deadline=""):
    skill = skill.strip().lower()
    if not skill or not task.strip():
        return {"error": "Task and required skill are needed."}
    people = [row for row in read_rows("employees.csv")
        if skill in str(row.get("skills", "")).lower().split("|")
        and str(row.get("available", "")).lower() in {"true", "1", "yes"}
        and number(row.get("tasks", 0)) < number(row.get("max_tasks", 5))]
    if not people:
        return {"escalation": True, "message": "No available employee has capacity and the required skill."}
    person = min(people, key=lambda row: number(row.get("tasks", 0)))
    return {"assigned_employee": person["name"], "required_skill": skill,
        "current_tasks": number(person.get("tasks", 0)), "task": task,
        "priority": priority, "deadline": deadline}


def performance_report():
    logs = read_rows("execution_logs.csv")
    if not logs:
        return {"message": "No execution logs are available."}
    failed = [row for row in logs if str(row.get("error", "")).lower() in {"true", "1", "yes"}]
    avg = sum(number(row.get("seconds", 0)) for row in logs) / len(logs)
    errors = Counter(row.get("message") or "Unknown error" for row in failed)
    tips = []
    if len(failed) / len(logs) > .1:
        tips.append("Investigate the failure rate.")
    if avg > 5:
        tips.append("Investigate slow workflows.")
    return {"total_runs": len(logs), "failed_runs": len(failed),
        "failure_rate_percent": round(len(failed) / len(logs) * 100, 2),
        "average_seconds": round(avg, 2), "frequent_errors": dict(errors),
        "recommendations": tips or ["No thresholds were exceeded."]}




