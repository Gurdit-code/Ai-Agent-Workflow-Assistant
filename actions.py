def validate_prices(products=None):
    products = {str(row.get("sku", "")).strip(): row
        for row in read_rows("prices.csv") if str(row.get("sku", "")).strip()}
    vendors = {str(row.get("sku", "")).strip(): row
        for row in read_rows("vendor_prices.csv") if str(row.get("sku", "")).strip()}
    results, exceptions, unmatched = [], [], []
    for sku in sorted(products.keys() - vendors.keys()):
        unmatched.append({"sku": sku, "error": "No vendor price found."})
    for sku in sorted(vendors.keys() - products.keys()):
        unmatched.append({"sku": sku, "error": "No internal product price found."})
    for sku in sorted(products.keys() & vendors.keys()):
        product, vrow = products[sku], vendors[sku]
        price = number(product.get("price"))
        vendor = number(vrow.get("vendor_price"))
        if price <= 0:
            exceptions.append({"sku": sku,
                "error": "Internal price must be greater than zero."})
            continue
        diff = abs(vendor - price) / price * 100
        row = {"sku": sku, "internal_price": price,
            "vendor_price": vendor, "difference_percent": round(diff, 2),
            "flagged": diff > 10}
        results.append(row)
        if row["flagged"]:
            exceptions.append(row)
    return {"validated_products": results, "exceptions": exceptions,
        "unmatched_skus": unmatched}

def process_vendor_file(file_path=None):
    files = []
    if file_path:
        files.append(Path(file_path))
    files.extend([DATA_DIR / "vendor.csv", DATA_DIR / "vendor.xlsx"])

    source = next(
        (path for path in files if path.exists() and path.is_file()),
        None)
    if source is None:
        return {"error": (
                "Upload a vendor CSV/XLSX file in the UI, or place "
                "vendor.csv/vendor.xlsx in the data folder."
            )}

    try:
        if source.suffix.lower() == ".csv":
            data = pd.read_csv(source)
        elif source.suffix.lower() in {".xlsx", ".xlsm"}:
            data = pd.read_excel(source)
        else:
            return {"error": "Unsupported file type. Use CSV or XLSX."}
    except Exception as error:
        return {"error": f"Could not read vendor file: {error}"}

    data.columns = (data.columns.astype(str).str.strip().str.lower()
                    .str.replace(r"[\s\-]+", "_", regex=True))
    
    required = {"sku", "product_name"}
    if not required.issubset(data.columns):
        return {"error": "Required columns are missing.",
            "required": sorted(required),
            "found": list(data.columns)}

    for column in required:
        data[column] = data[column].fillna("").astype(str).str.strip()

    valid = (data["sku"] != "") & (data["product_name"] != "")
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    clean_path = OUTPUT_DIR / "cleaned_vendor.csv"
    invalid_path = OUTPUT_DIR / "invalid_vendor_rows.csv"
    data[valid].to_csv(clean_path, index=False)
    data[~valid].to_csv(invalid_path, index=False)

    return {"source_file": source.name,
        "total_rows": int(len(data)),
        "valid_rows": int(valid.sum()),
        "invalid_rows": int((~valid).sum()),
        "cleaned_file": "outputs/cleaned_vendor.csv",
        "invalid_rows_file": "outputs/invalid_vendor_rows.csv"}


def product_description(name="", category="", material="", color="", audience=""):
    name = name.strip()
    if not name:
        return {"error": "Product name is required."}
    missing = [label for value, label in (
        (category, "category"), (material, "material"),
        (color, "color"), (audience, "target audience")) if not value]
    from agent import generate_product_copy
    generated = generate_product_copy({
        "product_name": name, "category": category, "material": material,
        "color": color, "target_audience": audience})
    return {**generated, "missing_attributes": missing,
        "note": "Generated by Gemini using only the supplied attributes."}


